package com.office.ex;

public class Variable {
	
	public static void main(String[] args) {
		
		//	변수
		int mynum = 1;			//	변수 정의
		int mynum2 = 2;
		
		System.out.println(mynum+mynum2);	//3
		
		/*
		변수한, 메모리의 특정 공간을 뜻한다.
		변수명이란, 메모리 주소 대신 인간이 붙인 이름이다.
		변수 정의 문법
		데이터 타입 변수명 = 데이터;
		
		변수 정의 = 변수 선언 + 변수 초기화
		변수 선언: int mynum
		변수 초기화: nynum = 1
		= : 할당 연산자
		*/
		
		// 변수 선언
		int num1;
		
		// 변수 초가화
		num1= 10;
		
		// 정수 : int
		// 실수 : float
		// 문자 : char
		// 문자열 : string
		
		int score = 10;
		
		float pi = 3.14f;
		
		char a = 'a';
		
		String str = "asdfg";
		
		// 내 이름(홍길동)
		String myName = "홍길동";
		
		// 1학기 수학 점수
		int myScore = 85;
		
		// 나의 신장(1.88);
		float myHeight = 1.88f;
		
		// 내가 제일 좋아하는 알파벳(J)
		char myFavorityAlphabet = 'J';
	}

}
