package com.office.ex;

public class MainClass {
	
	// 프로그램의 시작이다
	public static void main(String[] args) {
		
		// 콘솔에 데이터를 출력가능
		System.out.println("Hello java~");
		
		/*
		 	Class란,
		 	클래스는 프로그램을 구성하는 단위 입니다.
		 	그리고 자바 프로그램에서는 반드시 하나 이상 있어야 합니다.
		 */
		
		/*
		 	클래스 기본 형식
		 	public class 클래스이름{
		 
		 	}
		 */
		
		/*
			키워드란,
			특정한 목적으로 정의된 예약러를 말합니다.
			그래서 우리 개발자는 함부로 사용할 수 없다.
		*/
		
		/*
			클래스 이름 작명 규칙
			1. 클래스 이름은 영문 대문자로 시작한다.
			Hello, H2llo, Hello2 (모두 가능)
			2hello	(불가)
			
			2. 특수문자 사용 금지. 단, $, _는 사용가능(하지만 비추천)
			_Hello, H_ello, Hello_ (가능)
			_Hello, H_ello, Hello_ (가능)
			
			@Hello, ^^Hello (불가능)
			
			3. 클래스 이름은 클래스의 기능을 알 수 있도록 작명한다.
			계산기(calculator), 예약(reservation), 결제(payment)
			파일업로드(FileUpLoad)
		*/
		
		/*
			; 이란
			종결자라고 한다.
			안녕하세요. ==> 프로그램 구문의 끝을 나타낼 때 ;으로 구문의 끝을 나타낸다.
		*/
		
		System.out.println("Hello 자바");
		
		/* <- 여러줄 주석 (단축키: 컨트롤 + 쉬프트 + /)
		 	주석
			//: 한줄 주석 (단축키 컨트롤 + /)
		*/
		
	}

}
